# Pure helpers for the installed service's configuration paths. No side effects, so they can be tested without
# installing anything (see config-helpers.tests.ps1). Compatible with Windows PowerShell 5.1.
#
# NOTE: PowerShell variable names are case-insensitive. An earlier installer reused `$dataDir` for a sub-folder and
# silently overwrote the `-DataDir` parameter, so logs were written inside the user-writable data folder. Keep the
# data ROOT and its sub-folders in clearly different names, and keep the path rules here, where they are tested.

function ConvertTo-TomlPath {
    param([string]$Path)
    return ($Path -replace '\\', '/')
}

# Where the service keeps its files, relative to the data root (default C:\ProgramData\Syntrac):
#   data\syntrac.db   the user may modify (SQLite needs to create the WAL -shm file for an unelevated reader)
#   logs\             SIBLING of data\, not inside it: the user may only read it
function Get-ExpectedConfigPaths {
    param([Parameter(Mandatory = $true)][string]$DataRoot)
    $databaseFolder = Join-Path $DataRoot 'data'
    return [pscustomobject]@{
        Database = ConvertTo-TomlPath (Join-Path $databaseFolder 'syntrac.db')
        Logs     = ConvertTo-TomlPath (Join-Path $DataRoot 'logs')
    }
}

function Get-ConfigValue {
    param([string]$ConfigText, [string]$Key)
    $match = [regex]::Match($ConfigText, '(?m)^\s*' + [regex]::Escape($Key) + '\s*=\s*"([^"]*)"')
    if ($match.Success) { return $match.Groups[1].Value }
    return $null
}

# True when the config's database_path and log_dir are exactly the expected ones.
function Test-ConfigPaths {
    param([string]$ConfigText, [string]$Database, [string]$Logs)
    return ((Get-ConfigValue $ConfigText 'database_path') -eq $Database) -and ((Get-ConfigValue $ConfigText 'log_dir') -eq $Logs)
}

function New-ConfigText {
    param([string]$Template, [string]$Database, [string]$Logs)
    $header = "# Generated by install-service.ps1. Edit as an administrator; restart the service to apply.`r`n" +
        "database_path = `"$Database`"`r`nlog_dir = `"$Logs`"`r`n`r`n"
    return $header + $Template
}