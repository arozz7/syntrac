# Pure helpers for the installed service's configuration paths. No side effects, so they can be tested without
# installing anything (see config-helpers.tests.ps1). Compatible with Windows PowerShell 5.1.
#
# NOTE: PowerShell variable names are case-insensitive. An earlier installer reused `$dataDir` for a sub-folder and
# silently overwrote the `-DataDir` parameter, so logs were written inside the user-writable data folder. Keep the
# data ROOT and its sub-folders in clearly different names, and keep the path rules here, where they are tested.

function ConvertTo-TomlPath {
    param([string]$Path)
    return ($Path -replace '\\', '/')
}

# Where the service keeps its files, relative to the data root (default C:\ProgramData\Syntrac):
#   data\syntrac.db   the user may modify (SQLite needs to create the WAL -shm file for an unelevated reader)
#   logs\             SIBLING of data\, not inside it: the user may only read it
function Get-ExpectedConfigPaths {
    param([Parameter(Mandatory = $true)][string]$DataRoot)
    $databaseFolder = Join-Path $DataRoot 'data'
    return [pscustomobject]@{
        Database = ConvertTo-TomlPath (Join-Path $databaseFolder 'syntrac.db')
        Logs     = ConvertTo-TomlPath (Join-Path $DataRoot 'logs')
    }
}

function Get-ConfigValue {
    param([string]$ConfigText, [string]$Key)
    $match = [regex]::Match($ConfigText, '(?m)^\s*' + [regex]::Escape($Key) + '\s*=\s*"([^"]*)"')
    if ($match.Success) { return $match.Groups[1].Value }
    return $null
}

# True when the config's database_path, log_dir and pipe_allowed_sid are exactly the expected ones. A config from an
# older installer (no pipe_allowed_sid) therefore counts as wrong and is regenerated.
function Test-ConfigPaths {
    param([string]$ConfigText, [string]$Database, [string]$Logs, [string]$UserSid)
    return ((Get-ConfigValue $ConfigText 'database_path') -eq $Database) -and
        ((Get-ConfigValue $ConfigText 'log_dir') -eq $Logs) -and
        ((Get-ConfigValue $ConfigText 'pipe_allowed_sid') -eq $UserSid)
}

# The data root an installed config points at (the folder holding data\syntrac.db and logs\), or $null if the config
# does not follow that layout. Lets the scripts keep using a relocated data root instead of dragging it back to the
# default.
function Get-DataRootFromConfig {
    param([string]$ConfigText)
    $database = Get-ConfigValue $ConfigText 'database_path'
    if (-not $database) { return $null }
    $normal = $database -replace '/', '\'
    $tail = '\data\syntrac.db'
    if (-not $normal.EndsWith($tail, [StringComparison]::OrdinalIgnoreCase)) { return $null }
    return $normal.Substring(0, $normal.Length - $tail.Length)
}

# Sets a `key = "value"` line, keeping everything else exactly as it was (comments, other settings, line endings).
# A commented-out key does not count as present; if the key is missing it is added at the top.
function Set-ConfigValue {
    param([string]$ConfigText, [string]$Key, [string]$Value)
    $pattern = '(?m)^[ \t]*' + [regex]::Escape($Key) + '[ \t]*=[ \t]*"[^"]*"'
    $line = "$Key = `"$Value`""
    if ([regex]::IsMatch($ConfigText, $pattern)) {
        # A MatchEvaluator, so characters like $ in the value are written literally.
        $evaluator = [System.Text.RegularExpressions.MatchEvaluator]{ param($match) $line }
        return [regex]::Replace($ConfigText, $pattern, $evaluator)
    }
    return $line + "`r`n" + $ConfigText
}

# Points an existing config at a new data root. Only the database and log paths change.
function Set-ConfigPaths {
    param([string]$ConfigText, [string]$Database, [string]$Logs)
    $text = Set-ConfigValue -ConfigText $ConfigText -Key 'database_path' -Value $Database
    return Set-ConfigValue -ConfigText $text -Key 'log_dir' -Value $Logs
}

function New-ConfigText {
    param([string]$Template, [string]$Database, [string]$Logs, [string]$UserSid)
    $header = "# Generated by install-service.ps1. Edit as an administrator; restart the service to apply.`r`n" +
        "database_path = `"$Database`"`r`nlog_dir = `"$Logs`"`r`npipe_allowed_sid = `"$UserSid`"`r`n`r`n"
    return $header + $Template
}